// Generates site/js/points.js from config/cities/dar_es_salaam.json, the same
// file the Python collector reads. The site imports the generated module so the
// page makes no data request, and test/points.test.mjs fails if the two drift.
//
//   node tools/build-points.mjs          write the module
//   node tools/build-points.mjs --check  exit 1 if the module is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = new URL('../config/cities/dar_es_salaam.json', import.meta.url);
const target = new URL('../site/js/points.js', import.meta.url);

export function render() {
  const points = JSON.parse(readFileSync(source, 'utf8'));
  const rows = points
    .map((p) => `  ${JSON.stringify({ name: p.name, lat: p.lat, lon: p.lon, category: p.category })},`)
    .join('\n');
  return (
    '// Generated by tools/build-points.mjs from config/cities/dar_es_salaam.json.\n' +
    '// Do not edit by hand. Coordinates derive from OpenStreetMap road geometry.\n' +
    `export const POINTS = [\n${rows}\n];\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const output = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
    if (current !== output) {
      console.error('site/js/points.js is out of date. Run: node tools/build-points.mjs');
      process.exit(1);
    }
    console.log('site/js/points.js is up to date');
  } else {
    writeFileSync(target, output);
    console.log(`wrote ${fileURLToPath(target)}`);
  }
}
